-- This script is executed automatically by the official PostgreSQL image
-- when the database volume is initialized for the first time.

CREATE TABLE IF NOT EXISTS agents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_seen TIMESTAMP WITH TIME ZONE NOT NULL,
    agent_name VARCHAR(100) NOT NULL,
    hostname VARCHAR(100) NOT NULL,
    ipaddress VARCHAR(50) NOT NULL,
    os VARCHAR(100) NOT NULL,
    kernel VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS measurements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id INTEGER NOT NULL REFERENCES agents(id),
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    cpu DOUBLE PRECISION NOT NULL,
    memory DOUBLE PRECISION NOT NULL,
    disk DOUBLE PRECISION NOT NULL,
    network_in BIGINT NOT NULL,
    network_out BIGINT NOT NULL,
    network_in_mbps DOUBLE PRECISION NOT NULL,
    network_out_mbps DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS processes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    measurement_id INTEGER NOT NULL REFERENCES measurements(id),
    cpu DOUBLE PRECISION NOT NULL,
    memory DOUBLE PRECISION NOT NULL
);
